// Regenerates src/vendor/leaflet.ts from node_modules/leaflet and node_modules/h3-js (run after updating them):
//   node scripts/embed-leaflet.js
// Leaflet is embedded in the app instead of loaded from a CDN, so the map works on networks that block CDNs.
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'node_modules', 'leaflet');
const pkg = require(path.join(dir, 'package.json'));
const safe = (s) => s.replace(/<\/(script|style)/gi, '<\\/$1'); // must not close the inline tag
const js = safe(fs.readFileSync(path.join(dir, 'dist', 'leaflet.js'), 'utf8'));
const css = safe(fs.readFileSync(path.join(dir, 'dist', 'leaflet.css'), 'utf8'));
const license = fs.readFileSync(path.join(dir, 'LICENSE'), 'utf8');

// h3-js: draws hexagons from H3 cell ids (the server sends ids, not geometry)
const h3dir = path.join(__dirname, '..', 'node_modules', 'h3-js');
const h3pkg = require(path.join(h3dir, 'package.json'));
const h3js = safe(fs.readFileSync(path.join(h3dir, 'dist', 'h3-js.umd.js'), 'utf8'));
const h3license = fs.readFileSync(path.join(h3dir, 'LICENSE'), 'utf8').split('\n').slice(0, 3).join(' ').trim();

const out = `
// Generated by scripts/embed-leaflet.js — do not edit.
// Leaflet ${pkg.version}, https://leafletjs.com
/*
${license.trim()}
*/
export const LEAFLET_VERSION = ${JSON.stringify(pkg.version)};
export const LEAFLET_CSS = ${JSON.stringify(css)};
export const LEAFLET_JS = ${JSON.stringify(js)};
// h3-js ${h3pkg.version}, https://github.com/uber/h3-js — ${h3license}
export const H3_JS = ${JSON.stringify(h3js)};
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'vendor', 'leaflet.ts'), out);
console.log(`src/vendor/leaflet.ts: Leaflet ${pkg.version} + h3-js ${h3pkg.version}, ${Math.round(out.length / 1024)} KB`);
